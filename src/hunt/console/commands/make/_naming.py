from __future__ import annotations

import keyword
import re
import time

import click

_IDENTIFIER_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_COMMAND_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9:_-]*$")

_last_epoch: int = 0


def validate_identifier(value: str, kind: str = "name") -> str:
    """Return *value* if it is a safe Python identifier, else abort the command.

    Generator arguments end up in file names, class names, column names and
    table names inside generated source code. Anything other than
    ``[A-Za-z_][A-Za-z0-9_]*`` (path separators, quotes, dots, spaces, Python
    keywords) is rejected before any file is written.
    """
    if (
        not isinstance(value, str)
        or not _IDENTIFIER_RE.match(value)
        or keyword.iskeyword(value)
        or not value.strip("_")
    ):
        raise click.BadParameter(
            f"{value!r} is not a valid {kind}. Use letters, digits and underscores only, "
            "starting with a letter or underscore, and avoid Python keywords."
        )
    return value


def validate_command_name(value: str) -> str:
    """Validate a console command signature such as ``send:emails``."""
    if not isinstance(value, str) or not _COMMAND_RE.match(value):
        raise click.BadParameter(f"{value!r} is not a valid command name. Use letters, digits, ':', '-' and '_' only.")
    return value


def migration_timestamp() -> str:
    """Return the filename prefix shared by every migration generator.

    The format is ``YYYY_MM_DD_HHMMSS``. Migrations run in filename order, so
    every generator must use this one scheme; mixing it with compact
    (``YYYYMMDDHHMMSS``) or epoch prefixes makes later migrations sort before
    earlier ones. The fixed ``0001_`` … ``0199_`` prefixes written by
    ``hunt new`` and the starter kits always sort before any timestamp.

    Two calls within the same second (and process) return increasing values so
    files generated by one command keep their creation order.
    """
    global _last_epoch
    seconds = max(int(time.time()), _last_epoch + 1)
    _last_epoch = seconds
    return time.strftime("%Y_%m_%d_%H%M%S", time.localtime(seconds))
