from __future__ import annotations

from pathlib import Path

import click


@click.command("make:2fa-controllers")
@click.option("--force", is_flag=True, help="Overwrite files that already exist")
@click.option("--dry-run", is_flag=True, help="Preview files without writing them")
def make_two_factor_command(force: bool, dry_run: bool) -> None:
    """Scaffold two-factor authentication controllers, templates, and routes."""
    from hunt.console.commands.make._output import output

    output.configure(dry_run=dry_run)
    cwd = Path.cwd()
    _write_controllers(cwd, force)
    _write_templates(cwd, force)
    _write_routes_snippet(cwd, force)
    _write_migration(cwd)
    click.echo("\n  Two-factor authentication scaffolded.")
    click.echo("  Next steps:")
    click.echo("    1. Run the generated migration: hunt migrate")
    click.echo("    2. Register the routes: call `register(router)` from routes/two_factor.py in bootstrap/app.py")
    click.echo("    3. Make sure your login controller redirects to /two-factor/challenge when")
    click.echo("       Auth.two_factor_pending() is true after a failed Auth.attempt()")
    click.echo("       (the controller generated by `hunt new` already does).")
    click.echo("    4. Add EnsureTwoFactorAuthenticated to your global middleware if desired")


def _write(dest: Path, content: str, label: str, force: bool) -> None:
    """Write through the shared output context; existing files are kept unless --force is given."""
    from hunt.console.commands.make._output import output

    if force and dest.exists() and not output.dry_run:
        dest.write_text(content, encoding="utf-8")
        output.echo(f"  Overwrote {label.split(' ', 1)[-1].strip()}: {dest.relative_to(Path.cwd())}")
        return
    output.write(dest, content, label=label)


def _write_controllers(cwd: Path, force: bool = False) -> None:
    dest = cwd / "app" / "controllers" / "two_factor_controller.py"
    _write(dest, _CONTROLLER_STUB, "Created Controller", force)


def _write_templates(cwd: Path, force: bool = False) -> None:
    src = Path(__file__).parent.parent.parent.parent / "views" / "auth" / "two_factor"
    templates_dir = cwd / "resources" / "views" / "auth" / "two_factor"
    for html_file in sorted(src.glob("*.html")):
        _write(templates_dir / html_file.name, html_file.read_text(encoding="utf-8"), "Created Template  ", force)


def _write_routes_snippet(cwd: Path, force: bool = False) -> None:
    dest = cwd / "routes" / "two_factor.py"
    _write(dest, _ROUTES_STUB, "Created Routes    ", force)


def _write_migration(cwd: Path) -> None:
    from hunt.console.commands.make._naming import migration_timestamp
    from hunt.console.commands.make._output import output

    migrations = cwd / "database" / "migrations"
    suffix = "_add_two_factor_to_users_table.py"
    existing = sorted(migrations.glob(f"*{suffix}")) if migrations.is_dir() else []
    if existing:
        # A second copy would try to add the same columns again.
        output.echo(f"  Already exists: {existing[0].relative_to(cwd)}")
        return
    output.write(migrations / f"{migration_timestamp()}{suffix}", _MIGRATION_STUB, label="Created Migration ")


